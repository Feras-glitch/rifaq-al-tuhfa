# -*- coding: utf-8 -*-
"""9.39.10: تصحيحات المادة العلمية من المراجعة الشاملة، تُطبَّق على كل نسخ المنهج معًا:
المصدر JSON، وبيانات التطبيق، والنسخة التجريبية، ونسخة الاستوديو. قابل لإعادة التشغيل؛ ويتحقق من عدد المواضع.
شغّله من جذر المستودع ثم tools/rebuild_html.py
"""
import json, re, sys

SRC = 'curriculum/منهج_المرحلة1_كامل_معتمد_v1.3.json'
APP = ['app/تطبيق_الطالب_والمعلم_v9.39.html', 'app/تجربة_المرحلة1_للهاتف_v9.39.html']
STUDIO = 'studio/استوديو_المشرف_v9.39.html'

# ضبط المتن: يكسر الوزن أو يخالف النص المتداول (61 بيتًا). (القديم، الجديد، عدد المواضع المتوقع في نصوص المتن)
MATN = [
    ('كَلِمَةٍ', 'كِلْمَةٍ', 4),                                   # الأبيات 11، 43، 44، 50 (والبيت 15 «كِلْمِ» مضبوط أصلًا)
    ('الْأُولَى سَمِّهَا قَمَرِيَّهْ', 'الاُولَى سَمِّهَا قَمْرِيَّهْ', 1),  # البيت 28
    ('وَاللَّامَ الْأُخْرَى', 'وَاللَّامَ الاُخْرَى', 1),             # البيت 28
    ('مِنْ إِبْغِ', 'مِنِ ابْغِ', 1),                             # البيت 25: همزة وصل
    ('وَرَمْزُهَا فَعِ', 'وَرَمْزَهَا فَعِ', 1),                   # البيت 26: مفعول به
    ('مِنْ لَفْظِ وَايْ', 'مِنْ لَفْظِ وَايٍ', 1),                 # البيت 39
    ('وَعَيْنٌ ذُو', 'وَعَيْنُ ذُو', 1),                          # البيت 54
    ('الثُّلَاثِيِّ لَا', 'الثُّلَاثِي لَا', 1),                   # البيت 55
]

def fix(secs):
    by = {}
    for s in secs:
        for x in (s.get('items') or []) + (s.get('questions') or []):
            by[x['id']] = (s, x)
    done = []
    # 1) المتن
    for old, new, n in MATN:
        cnt = 0
        for s in secs:
            for it in s.get('items') or []:
                if it.get('type') == 'poem' and old in it['text']:
                    cnt += it['text'].count(old); it['text'] = it['text'].replace(old, new)
        already = sum(it['text'].count(new) for s in secs for it in (s.get('items') or []) if it.get('type') == 'poem')
        if cnt not in (0, n) or (cnt == 0 and already < n):
            sys.exit('matn %s: replaced %d, expected %d (already %d)' % (old, cnt, n, already))
        done.append(old)
    # البيت 54 مقتبس في سؤالين
    for qid in ('q12b_2', 'i12b_3'):
        x = by[qid][1]
        for k in ('explanation', 'sentence'):
            if k in x: x[k] = x[k].replace('وَعَيْنٌ ذُو', 'وَعَيْنُ ذُو')
    # 2) «أكملَ ما تكون» اسم تفضيل ثابت للجنسين، لا فعل أمر يُؤنَّث
    d = by['s6_ghunna_matn'][1]
    d['desc'] = d['desc'].replace('<b>{أكمل|أكملي} ما تكون</b>', '<b>أكملَ ما تكون</b>')
    q = by['q6_1'][1]; q['explanation'] = q['explanation'].replace('نطيل الغنة {أكمل|أكملي} ما تكون.', 'نطيل الغنة أكملَ ما تكون.')
    assert '{أكمل|أكملي} ما تكون' not in json.dumps([d, q], ensure_ascii=False)
    # 3) لام الفعل: تُظهر إلا قبل اللام والراء (والمنهج نفسه يذكر «قُل رَّبِّ» في q_mut_1)
    d = by['s8_lam_matn'][1]
    d['desc'] = d['desc'].replace('📌 لام الفعل تظهر دائمًا.', '📌 لام الفعل (مثل «قُلْ نَعَمْ» و«الْتَقَى») تظهر، إلا إذا جاء بعدها لام أو راء فتُدغم، مثل «قُل رَّبِّ».')
    assert 'تظهر دائمًا' not in d['desc']
    q = by['q8_3'][1]
    q.update({'text': 'لام الفعل تظهر دائمًا، حتى لو جاء بعدها راء مثل «قُل رَّبِّ».', 'answer': False,
              'explanation': 'لام الفعل تظهر في نحو «قُلْ نَعَمْ» و«الْتَقَى» (بيت 29)، لكنها تُدغم إذا جاء بعدها لام أو راء، مثل «قُل رَّبِّ».'})
    q = by['q_lamfil_2'][1]
    q['explanation'] = 'لام الفعل تُظهَر هنا لأن بعدها نونًا، ولا تُدغم إلا إذا جاء بعدها لام أو راء. (الصافات 37:18)'
    # 4) الأنبياء بصيغة واحدة (ولا تدل الصيغة على الجواب)
    q = by['q13_3'][1]
    q['options'] = [o.replace(' ﷺ', ' عليه السلام') for o in q['options']]
    assert not any('ﷺ' in o for o in q['options'])
    # 5) التسلسل: لا يُختبر الطفل فيما لم يُدرَّس بعد
    q = by['i1_1'][1]
    q.update({'text': '{وصّل|وصّلي} كل كلمة بمعناها',
              'explanation': 'النون الساكنة نون عليها سكون مثل «مِنْ»، والتنوين نون نسمعها في آخر الاسم ولا نكتبها، وعلاماته ـً ـٍ ـٌ، ولهما أربعة أحكام: الإظهار والإدغام والإقلاب والإخفاء.',
              'pairs': [['النون الساكنة', 'نون عليها سكون مثل «مِنْ»'], ['التنوين', 'نون نسمعها في آخر الاسم ولا نكتبها'],
                        ['علامات التنوين', 'ـً ـٍ ـٌ'], ['أحكامهما', 'الإظهار والإدغام والإقلاب والإخفاء']]})
    s5 = next(s for s in secs if s['id'] == 's5_ikhfa')
    if not any(x['id'] == 'i5_4' for x in s5['questions']):
        s5['questions'].append({'id': 'i5_4', 'text': '{وصّل|وصّلي} كل حكم بحروفه (مراجعة الأحكام الأربعة)',
            'explanation': 'من الأبيات 7–15: الإظهار عند حروف الحلق، والإدغام عند يرملون، والإقلاب عند الباء، والإخفاء عند خمسة عشر حرفًا.',
            'points': 10, 'type': 'match',
            'pairs': [['الإظهار', 'حروف الحلق الستة'], ['الإدغام', 'يَرْمُلُونَ'], ['الإقلاب', 'الباء'], ['الإخفاء', 'خمسة عشر حرفًا']]})
    q = by['i9_1'][1]
    q.update({'text': '{وصّل|وصّلي} كل عنوان بما يناسبه',
              'explanation': 'الطبيعي: لا همز ولا سكون بعد حرف المد. البدل: الهمز قبل حرف المد. العوض: عند الوقف على تنوين النصب. وحروف المد ثلاثة: الألف والواو والياء (تجمعها «وَايٍ»).',
              'pairs': [['الطبيعي', 'لا همز ولا سكون بعده'], ['البدل', 'الهمز قبل حرف المد'], ['العوض', 'الوقف على تنوين النصب'], ['حروف المد', 'الألف والواو والياء']]})
    # 6) سؤال مكرر (q1_5 = q1_3 معنى وجوابًا) يُستبدل بسؤال عمّا يُدرَّس في القسم ولم يُسأل عنه
    q = by['q1_5'][1]; q.clear()
    q.update({'id': 'q1_5', 'type': 'true_false', 'text': 'التنوين نسمعه عند الوصل، ولا نسمعه عند الوقف.', 'answer': True,
              'explanation': 'التنوين «نونٌ ساكنةٌ تُلحقُها العربُ آخرَ الأسماءِ لفظًا لا خطًّا، ووصلًا لا وقفًا»: نسمعه إذا وصلنا، ولا ننطق النون إذا وقفنا.', 'points': 10})
    # 7) سؤال «ما لم يذكره المتن» فوق مستوى العمر → سؤال تعريف مباشر
    q = by['q_mut_1'][1]; q.clear()
    q.update({'id': 'q_mut_1', 'type': 'true_false', 'text': 'إذا تقارب الحرفان في المخرج واختلفا في الصفات سُمِّيا «متقاربين».', 'answer': True,
              'explanation': 'قال الناظم: «وَإِنْ يَكُونَا مَخْرَجًا تَقَارَبَا وَفِي الصِّفَاتِ اخْتَلَفَا يُلَقَّبَا مُتَقَارِبَيْنِ» (بيتا 31–32). ومن أمثلتهما اللام والراء في «قُل رَّبِّ».', 'points': 10})
    d = by['s8b_mithl_matn'][1]
    d['desc'] = d['desc'].replace('🔹 تقاربا في المخرج = <b>متقاربان</b>.', '🔹 تقاربا في المخرج واختلفا في الصفات = <b>متقاربان</b>.')
    assert 'واختلفا في الصفات = <b>متقاربان' in d['desc']
    return secs

def main():
    # المصدر
    src = json.load(open(SRC, encoding='utf-8'))
    fix(src['sections'])
    src['meta']['fixes_9_39_10'] = ('ضبط المتن وفق النص المتداول (كِلْمة ×4، قَمْرِيَّهْ والاُولى/الاُخرى، مِنِ ابْغِ، رَمْزَهَا، وَايٍ، وَعَيْنُ، الثُّلَاثِي)؛ '
        'لام الفعل تُظهر إلا قبل اللام والراء (q8_3 وشرح القسم وq_lamfil_2)؛ «أكملَ ما تكون» ثابتة للجنسين؛ «عليه السلام» لكل الخيارات في q13_3؛ '
        'i1_1 صار عن محتوى القسم، وانتقل محتواه القديم إلى i5_4 بعد تدريس الأحكام؛ i9_1 بلا المد اللازم (لم يُدرَّس بعد)؛ q1_5 بدل المكرر؛ q_mut_1 سؤال تعريف. '
        'المراجعة العلمية بتلقٍّ من شيخ ما زالت مطلوبة قبل التوزيع.')
    open(SRC, 'w', encoding='utf-8').write(json.dumps(src, ensure_ascii=False, indent=1))
    # التطبيق والنسخة التجريبية
    RX = re.compile(r'(var PACK_DATA = )(.*?)(;\n/\* ===PACK_DATA_END)', re.S)
    for f in APP:
        s = open(f, encoding='utf-8').read(); m = RX.search(s)
        pk = json.loads(m.group(2)); assert json.dumps(pk, ensure_ascii=False) == m.group(2)
        fix(pk['curriculum'])
        s = s[:m.start(2)] + json.dumps(pk, ensure_ascii=False) + s[m.end(2):]
        open(f, 'w', encoding='utf-8').write(s); print('curriculum fixed:', f)
    # الاستوديو
    s = open(STUDIO, encoding='utf-8').read()
    m = re.search(r'^(var CURRICULUM = )(.*)(;)$', s, re.M)
    cur = json.loads(m.group(2)); assert json.dumps(cur, ensure_ascii=False) == m.group(2)
    fix(cur)
    s = s[:m.start(2)] + json.dumps(cur, ensure_ascii=False) + s[m.end(2):]
    open(STUDIO, 'w', encoding='utf-8').write(s); print('curriculum fixed:', STUDIO)

if __name__ == '__main__':
    main()
